"""
GeoAI Actor-Critic Swarm State Definition.
"""
from typing import TypedDict, List

class SwarmState(TypedDict):
    """
    Shared state for the Actor-Critic Swarm.
    
    Keys:
        question (str): The initial user question or request.
        plan (List[str]): A list of tool names generated by the Planner to execute.
        draft_response (str): The raw response drafted by the Worker agent.
        review_feedback (str): The critique provided by the Reviewer agent.
        review_status (str): The status of the review (e.g., 'APPROVED', 'REJECTED').
        loop_count (int): Counter to prevent infinite loops between Worker and Reviewer.
        tool_payload (dict): The raw JSON/dict output from the latest spatial tool execution.
        frontend_payload (dict): The final validated spatial parameters to send to GeoServer.
    """
    question: str
    plan: List[str]
    draft_response: str
    review_feedback: str
    review_status: str
    loop_count: int
    tool_payload: dict
    frontend_payload: dict
